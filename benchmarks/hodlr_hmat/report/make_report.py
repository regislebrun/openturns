#!/usr/bin/env python3
"""Generate the LaTeX report for the three-way HODLR benchmark.

Reads the JSON files produced by /tmp/opencode/hodlrbench/hodlr_compare.cxx
(results/run_<n>_<d>.json), emits the figures and the data tables used by
report.tex.
"""
import json, glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.environ.get("HODLR_RESULTS", "/tmp/opencode/hodlrbench/results")
FIG = os.path.join(HERE, "figures")
os.makedirs(FIG, exist_ok=True)

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

PROVIDERS = [("ot_hodlr", "OpenTURNS HODLR"),
             ("ot_hmat", "OpenTURNS HMat"),
             ("hmat_oss", "hmat-oss direct")]
COLOR = {"ot_hodlr": "#1f77b4", "ot_hmat": "#ff7f0e", "hmat_oss": "#2ca02c"}

def load():
    runs = []
    for fn in sorted(glob.glob(os.path.join(RES, "run_*.json"))):
        runs.append(json.load(open(fn)))
    return runs

def g(d, prov, *keys, default=None):
    p = d[prov]
    for k in keys:
        if k in p and p[k] is not None:
            return p[k]
    return default

def oknum(v):
    if v is None:
        return False
    if isinstance(v, float) and (v != v or v in (float("inf"), float("-inf"))):
        return False
    return True

def fmt_ms(v):
    if not oknum(v):
        return "--"
    t = 1000.0 * v
    if t >= 100.0:
        return f"{t:.0f}"
    if t >= 1.0:
        return f"{t:.1f}"
    return f"{t:.2f}"

def fmt_e(v):
    if not oknum(v):
        return "--"
    if v == 0.0:
        return "0"
    return f"{v:.1e}"

def config_label(d):
    return f"{d['n']} / {d['dim']}D"

def fig_bar(runs, keys, fname, ylabel, nested=None):
    """Grouped bars: one cluster per config, one bar per provider."""
    labels = [config_label(d) for d in runs]
    x = range(len(runs))
    width = 0.26
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    for i, (prov, name) in enumerate(PROVIDERS):
        if nested is not None:
            vals = [ms(d[prov][nested]["time"]) for d in runs]
        else:
            vals = [ms(g(d, prov, *keys)) for d in runs]
        ax.bar([xi + (i - 1) * width for xi in x], vals, width, label=name, color=COLOR[prov])
    ax.set_xticks(list(x))
    ax.set_xticklabels(labels)
    ax.set_ylabel(ylabel)
    ax.set_yscale("log")
    ax.legend(fontsize=8, ncol=3, frameon=False)
    ax.grid(axis="y", alpha=0.3, which="both")
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, fname), bbox_inches="tight")
    plt.close(fig)

def ms(v):
    return 1000.0 * v

def main():
    runs = load()
    if not runs:
        sys.exit("no results found in " + RES)

    fig_bar(runs, ["assemble"], "assemble.pdf", "assembly time [ms]")
    fig_bar(runs, ["factorize_llt", "factorize_sym"], "factorize_llt.pdf", "Cholesky factorization time [ms]")
    fig_bar(runs, ["factorize_lu"], "factorize_lu.pdf", "LU factorization time [ms]")
    fig_bar(runs, ["solve_llt", "solve_sym"], "solve.pdf", "solve time [ms]")
    fig_bar(runs, ["kl_time"], "kl.pdf", "KL Lanczos total time [ms]", nested="kl")

    L = []
    L.append("%% GENERATED by make_report.py -- do not edit by hand.")
    L.append("")

    # T2: accuracy
    L.append("\\newcommand{\\tabacc}{")
    L.append("\\begin{tabular}{l l c c c c c}")
    L.append("\\toprule")
    L.append("\\multicolumn{2}{c}{} & \\multicolumn{4}{c}{relative error vs. dense} & \\\\")
    L.append("\\cmidrule(lr){3-6}")
    L.append("$n$ / dim & provider & gemv & solve & logdet & KL $\\lambda_1$ & $c_r$ \\\\")
    L.append("\\midrule")
    for i, d in enumerate(runs):
        lab = f"{d['n']} / {d['dim']}D"
        for j, (prov, name) in enumerate(PROVIDERS):
            ge = g(d, prov, "gemv_pre_err", "gemv_err", "gemv_sym_err")
            se = g(d, prov, "solve_err", "solve_sym_err")
            le = g(d, prov, "logdet_err", "logdet_sym_err")
            ke = g(d, prov, "kl_eig1_err", default=d[prov]["kl"]["eig1_err"])
            cr = g(d, prov, "compression_ratio")
            crs = f"{cr:.3f}" if oknum(cr) else "--"
            row = [lab if j == 0 else "", name, fmt_e(ge), fmt_e(se), fmt_e(le), fmt_e(ke), crs]
            L.append("        " + " & ".join(row) + " \\\\")
        if i != len(runs) - 1:
            L.append("        \\addlinespace")
    L.append("\\bottomrule")
    L.append("\\end{tabular}}")

    L.append("")

    # T3: timings
    L.append("\\newcommand{\\tabtime}{")
    L.append("\\begin{tabular}{l l c c c c c c c}")
    L.append("\\toprule")
    L.append("\\multicolumn{2}{c}{} & \\multicolumn{7}{c}{wall-clock time [ms]} \\\\")
    L.append("\\cmidrule(lr){3-9}")
    L.append("$n$ / dim & provider & assemble & Chol. & LU & gemv & solve & solveLower & logdet \\\\")
    L.append("\\midrule")
    for i, d in enumerate(runs):
        lab = f"{d['n']} / {d['dim']}D"
        for j, (prov, name) in enumerate(PROVIDERS):
            row = [lab if j == 0 else "", name,
                   fmt_ms(g(d, prov, "assemble")),
                   fmt_ms(g(d, prov, "factorize_llt", "factorize_sym")),
                   fmt_ms(g(d, prov, "factorize_lu")),
                   fmt_ms(g(d, prov, "gemv_pre", "gemv_llt")),
                   fmt_ms(g(d, prov, "solve_llt", "solve_sym")),
                   fmt_ms(g(d, prov, "solveLower_llt", "solveLower_sym")),
                   fmt_ms(g(d, prov, "logdet_llt", "getDiagonal", "logdet_sym"))]
            L.append("        " + " & ".join(row) + " \\\\")
        if i != len(runs) - 1:
            L.append("        \\addlinespace")
    L.append("\\bottomrule")
    L.append("\\end{tabular}}")

    L.append("")

    # T4: application-level views (routine bundles as used by the OT modules)
    L.append("\\newcommand{\\tabapp}{")
    L.append("\\begin{tabular}{l l c c c c}")
    L.append("\\toprule")
    L.append("\\multicolumn{2}{c}{} & \\multicolumn{4}{c}{end-to-end time [ms]} \\\\")
    L.append("\\cmidrule(lr){3-6}")
    L.append("$n$ / dim & provider & sampling & KL & log-lik. & regression \\\\")
    L.append("\\midrule")
    for i, d in enumerate(runs):
        lab = f"{d['n']} / {d['dim']}D"
        dense = d["dense"]
        L.append(f"        {lab} & dense & -- & {ms(dense['kl_time']):.0f} & -- & -- \\\\")
        for j, (prov, name) in enumerate(PROVIDERS):
            ass = ms(g(d, prov, "assemble"))
            fc = ms(g(d, prov, "factorize_llt", "factorize_sym"))
            ap = g(d, prov, "applyFactor")
            gv = ms(g(d, prov, "gemv_pre", "gemv_llt"))
            sl = ms(g(d, prov, "solveLower_llt", "solveLower_sym"))
            ld = ms(g(d, prov, "logdet_llt", "getDiagonal", "logdet_sym"))
            sv = ms(g(d, prov, "solve_llt", "solve_sym"))
            kl = ms(d[prov]["kl"]["time"])
            sampling = ass + fc + (ms(ap) if oknum(ap) else gv)
            loglik = ass + fc + sl + ld
            reg = ass + fc + sv
            row = [lab if j == 0 else "", name, f"{sampling:.0f}", f"{kl:.0f}", f"{loglik:.0f}", f"{reg:.0f}"]
            L.append("        " + " & ".join(row) + " \\\\")
        if i != len(runs) - 1:
            L.append("        \\addlinespace")
    L.append("\\bottomrule")
    L.append("\\end{tabular}}")

    L.append("")

    # T5: dense reference values
    L.append("\\newcommand{\\tabdense}{")
    L.append("\\begin{tabular}{l c c c c}")
    L.append("\\toprule")
    L.append("config & $n_{\\mathrm{grid}}$ & $\\log\\det A$ & $\\lambda_1$ & dense KL [ms] \\\\")
    L.append("\\midrule")
    for d in runs:
        dense = d["dense"]
        L.append(f"        {d['n']} / {d['dim']}D & {d['n']} & {dense['logdet']:.1f} & {dense['lambda1']:.4f} & {ms(dense['kl_time']):.0f} \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}}")

    L.append("")

    open(os.path.join(HERE, "data.tex"), "w").write("\n".join(L))
    print("wrote data.tex and figures for", len(runs), "configs")

if __name__ == "__main__":
    main()
